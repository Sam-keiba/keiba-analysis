@dataclass(frozen=True)
class TrackShape:
    """トラックの形（コーナーごとの外への張り出し方）。

    コーナーを4つの1/4楕円（1角・2角・3角・4角）に分け、それぞれの「横の張り出し」を
    トラックの高さの半分に対する倍率で持つ。1.0なら半円、大きいほどその角が外へ膨らみ、
    小さいほど角が急になる。向正面の長さと位置はこの4つの数字から決まるので、
    **角の組み合わせだけで競馬場ごとの形の違いを表せる**。

    数値はJRA公式「コース紹介」のコース図に描かれている形の特徴（どの角が大きく、
    どの角が急か）を数字で言い表したもので、**図そのものをなぞったものではない**。
    一周距離・直線距離は公式の数値をそのまま使うので、
    「直線が一周に占める割合」と「全体の大きさ」は実際のコースどおりになる。
    """

    corner_bulge: tuple[float, float, float, float]  # 1角・2角・3角・4角
    # コーナーのいちばん外側（頂点）の高さ。(1〜2角側, 3〜4角側) で、
    # +ならホームストレッチ寄り＝手前の角が急で奥の角が大きく回り込む形になる。
    # 「中山は4角が急」「京都外回りは3角が大きい」といった特徴はこれで表す。
    apex: tuple[float, float] = (0.0, 0.0)
    note: str = ""  # 形の特徴（コメント用）


# (venue_code, loop) -> TrackShape
