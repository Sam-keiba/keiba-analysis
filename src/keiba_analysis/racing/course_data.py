DEFAULT_SHAPE = TrackShape((1.0, 1.0, 1.0, 1.0), (0.0, 0.0), "標準的な楕円")


def shape_for(venue_code: str, loop: str) -> TrackShape:
    """その競馬場・コースの形。ダート（loopが空）は芝の内回りの形を使い回す。"""
    for key in ((venue_code, loop), (venue_code, ""), (venue_code, "inner")):
        if key in SHAPES:
            return SHAPES[key]
    return DEFAULT_SHAPE
